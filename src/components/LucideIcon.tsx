interface LucideIconProps extends Omit<SvgProps, 'viewBox'> {
  name: keyof typeof ICON_PATHS;
  size?: number;
  color?: string;
  strokeWidth?: number;
}

/**
 * Parse SVG path string and render SVG elements
 * This is a simplified parser for Lucide icons which use a consistent format
 */
function parseSvgPath(pathString: string, color: string, strokeWidth: number) {
  const elements: React.ReactElement[] = [];
  const regex = /<(\w+)([^>]*)\/?>(?:<\/\1>)?/g;
  let match;
  let index = 0;

  while ((match = regex.exec(pathString)) !== null) {
    const tagName = match[1];
    const attributes = match[2];

    // Parse attributes
    const attrs: Record<string, string> = {};
    const attrRegex = /(\w+)="([^"]*)"/g;
    let attrMatch;
    while ((attrMatch = attrRegex.exec(attributes)) !== null) {
      attrs[attrMatch[1]] = attrMatch[2];
    }

    const key = `${tagName}-${index++}`;
    const commonProps = {
      stroke: color,
      strokeWidth,
      strokeLinecap: 'round' as const,
      strokeLinejoin: 'round' as const,
      fill: 'none',
    };

    switch (tagName) {
      case 'circle':
        elements.push(
          <Circle
            key={key}
            {...commonProps}
            cx={attrs.cx}
            cy={attrs.cy}
            r={attrs.r}
          />
        );
        break;
      case 'line':
        elements.push(
          <Line
            key={key}
            {...commonProps}
            x1={attrs.x1}
            y1={attrs.y1}
            x2={attrs.x2}
            y2={attrs.y2}
          />
        );
        break;
      case 'path':
        elements.push(
          <Path
            key={key}
            {...commonProps}
            d={attrs.d}
          />
        );
        break;
      case 'polyline':
        elements.push(
          <Polyline
            key={key}
            {...commonProps}
            points={attrs.points}
          />
        );
        break;
      case 'polygon':
        elements.push(
          <Polygon
            key={key}
            {...commonProps}
            points={attrs.points}
          />
        );
        break;
      case 'rect':
        elements.push(
          <Rect
            key={key}
            {...commonProps}
            width={attrs.width}
            height={attrs.height}
            x={attrs.x}
            y={attrs.y}
            rx={attrs.rx}
            ry={attrs.ry}
          />
        );
        break;
    }
  }

  return elements;
}

export function LucideIcon({
  name,
  size = 24,
  color = '#000',
  strokeWidth = 2,
  ...props
}: LucideIconProps) {
  const pathString = ICON_PATHS[name];

  if (!pathString) {
    console.warn(`LucideIcon: Icon "${name}" not found`);
    return null;
  }

  return (
    <Svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      {...props}
    >
      {parseSvgPath(pathString, color, strokeWidth)}
    </Svg>
  );
}
